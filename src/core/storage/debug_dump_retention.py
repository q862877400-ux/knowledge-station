"""`debug_dump` 的**保留策略**（唯一所有者）——两类记录**各自清理**，互不挤占。

## 为什么要有这个模块（2026-09-25 实测的真缺陷）

`debug_dump` 一张表承载**两类完全不同的东西**：

* **外发审计**（`trigger_type='egress'`）：每次云端调用写一条，**量很大**
  （实测 998/1000）；
* **提问证据**（`trigger_type='user_export'`）：答案路径写的，带 `retrieval_result`
  （命中了哪些标准号+条款号）——**量小、但不可再生**。

原先**两处写入各自把整张表裁到最新 1000 行**（两处都硬编码 `LIMIT 1000`）。
⇒ 谁写得多谁说话：**外发审计把提问证据挤出去**。

**实测后果（2026-09-25 读真库，逐维计数）**：全表 1000 行里
`egress` **998 行 / 0 行带检索结果**、`user_export` **2 行 / 2 行带检索结果**
⇒ **提问证据只剩 2 条**，且那是**同一句测试提问问了两次**（真实使用语料为零）。
⚠ 更强的证据：**同一条查询在几小时前返回 8、后来只剩 2** ⇒ **中间有 6 行带证据的记录被删** ⇒
**销毁是正在发生的**。

⚠⚠ **"可查窗口"这个说法本身要小心——它由写入速率决定，实测过两个差 2000 倍的值**：
* **忙碌时**：仓库自己的记录写着"生产库 egress 记录约 **50 分钟**即写满一轮（实测）"
  （`server.py` 的说明 + 开发史 §），**2026-09-24 的库备份逐字吻合**
  （1000 行全 egress，range `09-16 00:10:51 ~ 01:00:26`）；
* **空闲期**：窗口会显得很长——**我第一版就是按空闲期误读成"约 9 天"的**（已更正）。
⇒ **正确说法：窗口 = 1000 行 ÷ 当时的写入速率**，论"天"没有意义。

⚠ 这不只是"少收了数据"，而是**收进来又被销毁**。而且它卡着两条线：
检索长周期计划 P1 的**盈亏平衡点**（真实目标里"多条定义"的比例）靠它算；
P5 的"真实提问分布"也把它列为前置。

## 修法

**按 `trigger_type` 各自清理**（`prune()`），于是：

* 外发审计**保 1000 条**（与原先同量级，审计视图不受影响）；
* 提问证据**保 5000 条**。⚠ **这个数是估的，不是实测**——**提问速率原理上不可测**
  （被销毁的就是它）；现存实测约 1 条/天。取 5000 是为了"远大于需要的上界"。
  存储：实测单行最大 **3,112 B** ⇒ 5000 行约 **15 MB**（**有界**，不会无限长）。

⚠ 两类相加上限 6000 行；这比原先的 1000 行**更大**，是**为了让提问证据活下来**
（旧行为下它与审计同寿——被审计挤掉）。

⚠⚠ **本改动当初的代价与它的修法（2026-09-26）**：上限变大曾让两种操作变慢 ——
因为**这张表原先没有任何索引**。复核实测 6000 行：审计导出 **205 ms**（1000 行时 17.6 ms）、
`record_egress` 单次 **1.2 → 19.4 ms（×16）**。
⇒ ✅ **已加索引**（`schema.sql` 的 `idx_debug_dump_type_created`）。⚠ **列必须放全**：
三种形态 × 四种读法实测（`var/tmp/probe-debug-dump-index.py`）表明，只放
`(trigger_type, created_at DESC)` 会让**导出全表变慢 1.07×**；把 ORDER BY 的 `dump_id` 也放进去
才是：**翻页 16× 快（39.1→2.4 ms）、游标翻页 8× 快、写入 4.5× 快（4.6→1.0 ms）、导出 0.99×（不变差）**。
（临时库 + 合成行 + 单机单跑 ⇒ 量级参考，非生产 SLA。）
"""
from __future__ import annotations

import sqlite3

#: 外发审计保留条数（与历史行为同量级）。
KEEP_EGRESS = 1000
#: 提问证据保留条数。**故意比审计大**：它不可再生，且 P1/P5 都要用。
KEEP_QUESTION_EVIDENCE = 5000

#: 两类记录的 `trigger_type` 取值（与 `egress_audit._AUDIT_TRIGGER_TYPES` 同口径；
#: 两份都对，但**各自的用途不同**：那份是"审计聚合时算不算外发记录"，
#: 这份是"清理时按谁分组"。改一处要想想另一处。）
TYPE_EGRESS = "egress"
TYPE_QUESTION = "user_export"


def prune(conn: sqlite3.Connection, trigger_type: str, keep: int) -> int:
    """只裁**这一类**记录到最新 `keep` 条；**不动别的类型**。返回删掉的条数。

    ⚠ 为什么必须带 `WHERE trigger_type = ?`：不带就是全表裁——那正是本缺陷的成因
    （外发审计量大 ⇒ 把提问证据挤出去）。**这条 `WHERE` 是修复的全部要点**，
    删掉它就等于退回旧行为。
    """
    cur = conn.execute(
        "DELETE FROM debug_dump WHERE trigger_type = ? AND dump_id NOT IN ("
        " SELECT dump_id FROM debug_dump WHERE trigger_type = ?"
        " ORDER BY created_at DESC, rowid DESC LIMIT ?)",
        (trigger_type, trigger_type, keep))
    return int(cur.rowcount or 0)
