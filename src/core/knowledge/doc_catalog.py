def ccs_range_of(code: str) -> tuple[str, str] | None:
    """CCS 具体类目（如 P16）→ 所属区间 (P15/19, 工程抗震、工程防火、人防工程)。"""
    import re as _re
    m = _re.match(r"^([A-Z])(\d{2})$", code)
    if not m:
        return None
    letter, num = m.group(1), int(m.group(2))
    for rng, name in CCS_RANGES.get(letter, []):
        mm = _re.match(r"([A-Z])(\d{2})/(\d{2})", rng)
        if mm and int(mm.group(2)) <= num <= int(mm.group(3)):
            return (rng, name)
    return None


