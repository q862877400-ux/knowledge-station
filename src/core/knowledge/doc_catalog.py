def _law_tier(doc) -> str:
    """第一级效力层级：优先 legal_hierarchy 映射；无则关键词推断；兜底 '未定级'。"""
    hier = doc.get("legal_hierarchy") or ""
    if hier in _HIER_TO_TIER:
        return _HIER_TO_TIER[hier]
    text = (doc.get("standard_name") or "") + (doc.get("standard_no") or "")
    if "宪法" in text:
        return "宪法及宪法相关法"
    if "司法解释" in text or "最高法" in text:
        return "司法解释"
    return "未定级"


def _law_dept(doc) -> str:
    """第二级法律部门：标题+领域标签命中关键词 → A~G；兜底 '未分类'。"""
    hay = " ".join([doc.get("standard_no") or "", doc.get("standard_name") or ""])
    tags = doc.get("domain_tags") or []
    hay += " " + " ".join(str(t) for t in tags if isinstance(t, str))
    for code, label, kws in _DEPT_KEYWORDS:
        if any(k in hay for k in kws):
            return label
    return "未分类"


def _law_domain_doc(doc) -> list[str]:
    """第三级业务/行业领域：取非 CCS 的领域标签；无则空列表（挂到'未细分'）。"""
    tags = doc.get("domain_tags") or []
    return [t for t in tags if isinstance(t, str)
            and not t.startswith("CCS:") and t not in _NON_DOMAIN]


