#: 反向索引：市名 → 省名（含去掉「市」的简称）
_CITY_TO_PROVINCE: dict[str, str] = {}
for _prov, _cities in PROVINCE_CITIES.items():
    for _c in _cities:
        _CITY_TO_PROVINCE[_c] = _prov
        _CITY_TO_PROVINCE.setdefault(_c.rstrip("市"), _prov)


def province_of_city(city_name: str) -> str | None:
    """由市名反查所属省。

    支持三种形态：全称（`天水市`）/ 去「市」（`天水`）/ 含后缀（`天水市人民政府`）。
    查不到返回 `None` —— **不猜，宁缺勿错**。
    """
    if not city_name:
        return None
    s = city_name.strip()
    if s in _CITY_TO_PROVINCE:
        return _CITY_TO_PROVINCE[s]
    # 去掉常见后缀再试
    for suf in ("人民政府", "政府", "市", "地区", "自治州", "盟"):
        if s.endswith(suf):
            t = s[: -len(suf)]
            if t in _CITY_TO_PROVINCE:
                return _CITY_TO_PROVINCE[t]
    # 前缀匹配（处理「天水市秦州区」这类）
    for k, v in _CITY_TO_PROVINCE.items():
        if len(k) >= 2 and s.startswith(k):
            return v
    return None


#: 严格意义的地级行政区数（不含**省直辖县级市**济源市）。
#:
#: ⚠ 与 `total_cities()` 的差就是济源市一个 —— 见模块文档的口径更正（spec 005 T603）。
#: 对外说"全国地级行政区有几个"时用这个；`count_by_city()` 的白名单用 `total_cities()`。
PREREFECTURE_COUNT_STRICT = 333


def total_cities() -> int:
    """**本表收录数**（334，含省直辖县级市济源市）。

    ⚠ 别把它当成"国家标准的地级行政区数"（那是 `PREREFECTURE_COUNT_STRICT = 333`）。
    本表多收济源市是因为它的**数据真的存在**，白名单漏了它会误判成"未知市"。
    """
    return sum(len(v) for v in PROVINCE_CITIES.values())
