#!/usr/bin/env bash
# 天津 enorth「政民零距离」· 逐部门限量采集
# ---------------------------------------------------------------------------
# 为什么逐部门：630,595 条 × 1.5s ≈ 263 小时，全量不可行；改为每部门 CAP 条、
# 跑完一个部门就落盘（harvest.py 在该次运行结束时写 data/），中断只损失当前部门。
#
# 用法：  bash tools/gov-qa/recon/tj-enorth-harvest.sh [CAP] [LIMIT]
#   CAP   每个部门最多取多少条（默认 1000）
#   LIMIT 单次 harvest 的总上限（默认 = CAP）
#
# 例：    bash tools/gov-qa/recon/tj-enorth-harvest.sh 1000        # 55 dept × 1000 ≈ 5.5 万条
#         TJ_ENORTH_DEPTS=1002001000000000 bash .../tj-enorth-harvest.sh 200  # 只跑和平区
# ---------------------------------------------------------------------------
set -u
cd "$(dirname "$0")/../../.." || exit 1          # → 仓库根（zcode）
P=".venv/Scripts/python.exe"
HARVEST="tools/gov-qa/harvest.py"

CAP="${1:-1000}"
LIMIT="${2:-$CAP}"

DEPTS=(
  1002040000000000 1002001000000000 1002004000000000 1002003000000000
  1002002000000000 1002005000000000 1002006000000000 1002010000000000
  1002011000000000 1002012000000000 1002013000000000 1002014000000000
  1002015000000000 1002017000000000 1002018000000000 1002016000000000
  1001019000000000 1001022000000000 1001007000000000 1001020000000000
  1001003000000000 1001023000000000 1001024000000000 1001004000000000
  1001005000000000 1001025000000000 1001034000000000 1001028000000000
  1001027000000000 1001029000000000 1001038000000000 1001031000000000
  1001030000000000 1001021000000000 1001032000000000 1001002000000000
  1001006000000000 1001008000000000 1001010000000000 1001011000000000
  1001001000000000 1001012000000000 1001060000000000 1001013000000000
  1001017000000000 1001014000000000 1001015000000000 1001016000000000
  1001018000000000 1001040000000000 1001037000000000 1001061000000000
  1001041000000000 1001043000000000 1001065000000000 1001063000000000
)

# 允许用 TJ_ENORTH_DEPTS 只跑子集（空格或逗号分隔均可）
if [ -n "${TJ_ENORTH_DEPTS:-}" ]; then
  DEPTS=(${TJ_ENORTH_DEPTS//,/ })
fi

echo "[enorth-harvest] dept ${#DEPTS[@]} 个，每 dept CAP=$CAP，单次 LIMIT=$LIMIT"
i=0
for did in "${DEPTS[@]}"; do
  i=$((i + 1))
  echo "=== [$i/${#DEPTS[@]}] dept=$did ==="
  TJ_ENORTH_DEPTS="$did" TJ_ENORTH_CAP="$CAP" \
    timeout 3600 "$P" "$HARVEST" --site tj-enorth --limit "$LIMIT"
  rc=$?
  echo "=== dept=$did done rc=$rc ==="
  sleep 2
done
echo "[enorth-harvest] 全部完成"
