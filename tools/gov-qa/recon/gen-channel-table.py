#!/usr/bin/env python
"""生成 `SITE-REGISTRY.md` 的**通道台账表**（spec 004 T052）。

## 为什么要有它

M1 要求「每个来源……**登记了「自报总量 + 上次落盘量」**」。
`channel.py` 里 `Channel` 已经有 `watermark_type` / `self_reported_total` 两个字段，
但 `SITE-REGISTRY.md` **一个都没登记**（实测 `watermark_type` 0 命中）
⇒ 接手的人得逐个读代码才知道每个通道靠什么做增量。

## 做法

从**代码**（`channel.py` 的注册表）与**语料**（`data/*.jsonl` 的实际条数）
生成一张表，写进 `SITE-REGISTRY.md` 的一个**受管区块**：
两个 HTML 注释标记之间的内容由本脚本全量重写，**区块之外一个字都不动**。

    python tools/gov-qa/recon/gen-channel-table.py           # 写文件
    python tools/gov-qa/recon/gen-channel-table.py --check   # 只核对，不写（门禁用）

`--check` 退出码：0 = 表是最新的；1 = 表过期（需重跑）。
"""
from __future__ import annotations

import argparse
import glob
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

from channel import load_channels                                       # noqa: E402
from common import ascii_kv, safe_print                                 # noqa: E402

REGISTRY = ROOT / "SITE-REGISTRY.md"
DATA = ROOT / "data"

BEGIN = "<!-- BEGIN CHANNEL-TABLE (generated by recon/gen-channel-table.py) -->"
END = "<!-- END CHANNEL-TABLE -->"

#: 水位类型的**人话解释**（接手的人不用读代码就知道它靠什么做增量）
WM_DOC = {
    "idset": "**已落盘 id 集合** —— 翻到「本批全已见过」就停（最稳，但不省请求）",
    "page": "**页号** —— 从水位记的页 +1 起翻（省请求；依赖站点页序稳定）",
    "since": "**时间** —— 只取比水位新的记录（依赖站点给可靠时间）",
}


def landed_counts() -> dict:
    """每个通道**实际落盘**多少条（按文件名前缀归到最长匹配的通道 key）。"""
    keys = sorted((c.key for c in load_channels()), key=len, reverse=True)
    out: dict = defaultdict(int)
    for p in glob.glob(str(DATA / "*.jsonl")):
        name = Path(p).name
        hit = next((k for k in keys if name.startswith(k + "-")), None)
        if hit is None:
            continue
        try:
            with open(p, encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    if line.strip().startswith("{"):
                        out[hit] += 1
        except OSError:
            continue
    return dict(out)


def render() -> str:
    chans = load_channels()
    landed = landed_counts()
    rows = sorted(chans, key=lambda c: (c.level, c.key))
    lines = [
        BEGIN,
        "",
        "### 通道台账（**本表由脚本生成，不要手改**）",
        "",
        f"共 **{len(chans)}** 个通道。生成命令："
        "`python tools/gov-qa/recon/gen-channel-table.py`",
        "",
        "⚠ 「已落盘」一列**随采集实时变化** ⇒ `--check` **不核对它**"
        "（否则并行采集时门禁会假红）。`--check` 只核对"
        "**通道清单 / 水位类型 / 自报总量 / 状态** 这些稳定列。",
        "",
        "| 通道 | 层级 | 归属 | 水位类型 | 增量靠什么 | 自报总量 | 已落盘 | 状态 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in rows:
        n = landed.get(c.key, 0)
        tot = c.self_reported_total
        tot_s = f"{int(tot):,}" if isinstance(tot, (int, float)) and tot else "—"
        wm = c.watermark_type or "idset"
        lines.append(
            f"| `{c.key}` | {c.level} | {c.region or '—'} | `{wm}` | "
            f"{WM_DOC.get(wm, '（未登记）')} | {tot_s} | {n:,} | {c.status} |")
    lines += ["", END, ""]
    return "\n".join(lines)


#: 「已落盘」列的位置（0-based，含首尾空串：`|` 切分后 index 7）
_LANDED_COL = 7


def _stable_part(block: str) -> str:
    """把「已落盘」一列抹掉后的表 —— `--check` 的比对基准。

    动机：该列**随采集实时变化**（并行采集进程一直在写），
    核对它会让门禁**在数据正常增长时假红**。
    ⇒ 只核对**稳定列**（通道清单 / 水位类型 / 自报总量 / 状态）。
    """
    out = []
    for ln in block.splitlines():
        if ln.startswith("| `"):
            cells = ln.split("|")
            if len(cells) > _LANDED_COL:
                cells[_LANDED_COL] = " · "
                out.append("|".join(cells))
                continue
        out.append(ln)
    return "\n".join(out)


def splice(old: str, block: str) -> str:
    """把受管区块换掉，**区块之外一个字不动**。"""
    i, j = old.find(BEGIN), old.find(END)
    if i < 0 or j < 0:
        # 首次：追加到文件末尾
        return old.rstrip("\n") + "\n\n" + block
    return old[:i] + block + old[j + len(END) + 1:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="生成 SITE-REGISTRY 的通道台账表（T052）")
    ap.add_argument("--check", action="store_true", help="只核对，不写")
    ap.add_argument("--quiet", action="store_true", help="机器可读")
    args = ap.parse_args(argv)

    old = REGISTRY.read_text(encoding="utf-8")
    new = splice(old, render())

    if args.check:
        # ⚠ **只核对稳定列**（见 `_stable_part` 的文档）：
        #   「已落盘」一列随采集实时变化，核对它会在数据正常增长时假红。
        ok = _stable_part(_block_of(old)) == _stable_part(_block_of(new))
        if args.quiet:
            ascii_kv({"TABLE_UP_TO_DATE": 1 if ok else 0})
        else:
            safe_print("通道台账表是最新的" if ok
                       else "通道台账表**已过期** —— 跑 `gen-channel-table.py` 重生成")
        return 0 if ok else 1

    REGISTRY.write_text(new, encoding="utf-8")
    safe_print(f"已写入 {REGISTRY}（{'无变化' if new == old else '已更新'}）")
    return 0


def _block_of(text: str) -> str:
    """取出受管区块的内容（不含标记行）。"""
    i, j = text.find(BEGIN), text.find(END)
    return text[i:j] if i >= 0 and j >= 0 else ""


if __name__ == "__main__":
    raise SystemExit(main())
