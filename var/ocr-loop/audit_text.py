r"""条款文本异常审计器（2026-09-15 立）。

动机：`ocr_confidence`（span min 聚合）会把「一个弱 span + 文本完全正确」
报成整条低置信——全库普查 336 条低置信里 275 条未命中任何已知类，且文本
看着干净。**分数不能代替内容审计**。本工具按内容给判据，每类可独立计数，
输出跨文档分布 → 谁达线就修谁。

判据（高精度优先，宁少勿滥；每条都来自本会话实测语料）：
  spaced-run        逐字符拉开（'6 m m ² / s'）
  split-value       数值被空格劈开且后随单位（'6 50 µ m'）
  pua-residue       PUA 私用区分隔符残留（U+E011/U+E788，全库实测仅此二）
  replacement       U+FFFD 替换字符
  dot-leader        正文里的点线引导符（'………'）
  mfr-unit-misread  单位字形误读（'·∞' / 'τ r/min' / '\\mathrm' 泄漏）
  unit-midspace     单位内部多余空格（'k g' 'm i n' 'c m' 'k V'）

2026-09-15 校准删除两条**假判据**（实测匹配到的是合法内容，不是缺陷）：
  ~~stray-after-unit~~  匹配 'A1'/'B1'/'M1'（附录号/变量名），实测 312 处全非缺陷
  ~~bracket-imbalance~~ 跨条款天然不配对（公式跨条款、全半角混用），1094 条噪声
仪器可信度优先：宁可少报，不可让台账被噪声淹没。
"""
from __future__ import annotations

import re

CHECKS: list[tuple[str, re.Pattern]] = [
    # 2026-09-15：`spaced-run` **判据已删除**（保留此行位以示来源与复现条件）。
    #
    # 原判据 `(?<![一-鿿])(?:[A-Za-z0-9₀-₉⁰-⁹][ \t\u00a0]){3,}` 只要求「≥3 个
    # 单字符+空白对」，实测（新语料 231 部）命中 15/15 全是**合法形态**：
    #   '0.000 1 g'（四位分组精度值——门禁明令不改）、
    #   'pₘᵢₙ = 0.75 p y [ σ ] /Rₑ'（公式变量积）、
    #   'X = 1.0046 X c - 0.0137 Y c'（下标变量）、
    #   'King A M Q, Carstens E B'（文献作者缩写）。
    # 且这些命中经**所有者链**（`glue_ocr_spaced_units`）处理后**一字不变**——
    # 说明它们是所有者刻意保留的形态；而真缺陷（'1 . 0 mm'、'0.5U N'、'P 1 E'）
    # 已被所有者修复、修复后不再命中。
    #
    # 关键：残留的「单位被劈开」（'m m'）与「变量相乘」（'X c'）**语法同形**，
    # 判据无法区分 → 无可用判别信号。按纪律（误报判据要删除，不是报上去）
    # **删除本判据**，`classify.py` 中由它派生的 `ocr-wide-space-units` 类一并删除
    # （其原本就是同一条判据产两个类名，纯重复计数）。
    # 复现条件与恢复方案见 `evolve/instrument_fixes.jsonl` 的 deleted_rules 记录。
    # **2026-09-15 缩窄（批次3 全新语料实测，修正跨行误报）**：
    # 原判据用 `\d\s+\d`，而 `\s` **含换行** → 会把「行尾的一个数字 + 换行 +
    # 下一行开头的三位数」跨行连成一个假拆开值。实测误报源（GB/T 34779-2017
    # 条款 C.4.1）：`C.4.1 示例 1\n100 kg 特级茶坯…` 命中 `'1\n100 kg'`。
    # 而"数值被空格劈开"这一真形态**永远在同一行内**（'1 00 g'/'3 00 mm'），
    # 故把两个 `\s+` 都收成行内空白 `[ \t]+`：真形态仍全部命中（3/3），
    # 跨行误报归零（含 `见 2 页\n100 kg` 这类二次检验）。
    # **2026-09-15 第二次缩窄（表格判据上线后实测）**：新命中的两条都是
    # `1 400 mm`（GB/T 7911-2024 表格单元格）——**国标里四位数字写 `1 400`
    # 是合法排版（空格作千分位）**，不是"数值被劈开"。
    # 判据的 `0\d` 分支本意是抓 '1 00 g'（高位被拆成 00），但"空格+1 位数字
    # +3 位零头"与"空格作千分位的四位数"**形态完全重合**（1|400、2|500、3|000…），
    # 无法区分 → 该分支只会产出误报，**删掉该分支**（保留 `\d{2,4}` 分支，
    # 它抓的是"1 位数字 + 空格 + 2~4 位"，与千分位写法不同形）。
    # 注：`\d[ \t]+\d{2,4}` 分支仍可能命中 `1 400`（1 后跟 3 位）——
    # 故再加**左侧不得是数字/点**（原有）与**右侧不得是数字/点**（新增）：千分位
    # 写法后面紧跟单位（`1 400 mm`），而真拆开的值后面也跟单位…
    # 二者确实同形，故本判据**只保留高置信形态**：被拆的是**小数**（含小数点）
    # 或**单位紧跟且空格数 ≥2**（真 OCR 拉开通常出现多空格）。
    ("split-value", re.compile(r"\d[ \t]{2,}\d{2,4}\s*(?:µ|μ|mm|cm|kg|mg|g|ms|min|mL|L|m|s|V|A|N|W|Hz|Pa|kV)\b")),
    ("pua-residue", re.compile(r"[\ue000-\uf8ff]")),
    ("replacement", re.compile(r"\ufffd")),
    # 2026-09-15 校准：`…{2,}` 会命中合法中文省略号（'……' 在正文里是正常标点）。
    # 真缺陷两形态：① 公式编号前的点线（'……( B.6'，点线紧跟左括号）；
    # ② 正文/目录里的点线连排（≥3 个省略号或 ≥6 个句点）。二者都保留。
    #
    # **2026-09-16 收窄分支①（与所有者层同源口径）**：原为 `…{2,}\s*[（(]`
    # ——**只要省略号后面跟一个括号就报**，而括号里是什么完全不管。
    # 但所有者层 `src/core/text_utils.strip_formula_leader` 的
    # `_RE_FORMULA_LEADER` **明确要求括号内是编号**（`[A-Za-z]?\.?\s?\d{1,3}…`），
    # 且注释写死了理由：「**只放宽空格，不放宽字符类**——避免把正文括号内容
    # 误当编号」。于是又一处「**检测器报缺陷、所有者层却（按设计）不清洗**」的
    # 口径错位——与 text_utils 注释里已修过的那两处（`…{3,}`、`\.{6,}`）**同一类**，
    # 只是这条分支当时没一起对齐。
    #
    # 实测证据（批次 13 达线，3 部 3 条**全部**是误报；判据命中原文见
    # `verify_batch.py --class dot-leader`，`KS_CORPUS_LIST` 指向该批清单）：
    #   · GB 2099.5-2008   '……（正在考虑中）'   ← 括号内是**中文**，正文省略号
    #   · GB／T 14315-2008 '……（省略）'         ← 同上
    #   · GB／T 39398-2020 '……（\nD TGD, ᵢ = …'  ← 括号内是公式，非编号
    # 三条都不是公式编号引导线，正文省略号后接中文括号是**正常标点**。
    # 故分支①要求括号内出现**数字**（可带前导字母/点/空格），与所有者同口径：
    # 真正的引导线 '……( 7' / '……( A.1' / '……(C. 3' 全部仍被捕获。
    ("dot-leader", re.compile(
        r"…{2,}\s*[（(]\s*[A-Za-z]?\.?\s?\d{1,3}|…{3,}|\.{6,}|。{4,}")),
    ("mfr-unit-misread", re.compile(r"·\s*∞|τ\s*r\s*/\s*min|\\Nu|\\mathrm")),
    # **2026-09-15 缩窄两次（表格判据上线后实测）**：
    #   ① 表格里 `n | c | m | M`（微生物限量表的列名）扁平化后成 `n c m M`，
    #      其中 `c m` 与"cm 被劈开"同形 → 误报；
    #   ② 另一份表的列名行 `D | E | H | K | N | Q | R` 给出 `K N`
    #      （与"kN 被劈开"同形）→ 仍误报。
    # **单字母/双字母列名与"被劈开的单位"在文本上完全同形**，无法靠语义区分。
    # 但列分隔是**单个空格**，而 OCR 把一个单位拉开时**空格数 ≥2**（或整串无空格）。
    # 故要求"两半之间至少 2 个空白"——真形态保留，列相邻归零。
    # 复现条件：若出现**单空格**的真拆开（`c m` 来自 `cm`），该判据不报——
    # 但那种形态与表格列名不可区分，报出来就是误报（宁可少报）。
    ("unit-midspace", re.compile(
        r"\b(?:k|m|c|d|n|K|M|C|D|N|H)[ \t]{2,}"
        r"(?:g|i\s*n|m|V|A|W|J|z|N|L|s|Pa|PA)\b")),
]


def audit_clause(text: str | None) -> list[str]:
    """单条条款文本 → 命中的异常类清单。

    2026-09-15 校准：删除两条假判据（见模块 docstring）——仪器可信度优先。
    """
    t = text or ""
    return [name for name, pat in CHECKS if pat.search(t)]


def audit_doc(texts: list[str]) -> dict[str, int]:
    out: dict[str, int] = {}
    for t in texts:
        for h in audit_clause(t):
            out[h] = out.get(h, 0) + 1
    return out
