def classify_qc(qc: dict) -> dict[str, dict]:
    """整份 qc 结果 → {类名: {count, evidence:[条款号...]}}。"""
    out: dict[str, dict] = {}
    for s in qc.get("low_samples") or []:
        for cls in classify_clause(s.get("clause") or "", s.get("head") or "",
                                   float(s.get("conf") or 1.0)):
            rec = out.setdefault(cls, {"count": 0, "evidence": []})
            rec["count"] += 1
            if len(rec["evidence"]) < 6:
                rec["evidence"].append(s.get("clause"))
    return out
