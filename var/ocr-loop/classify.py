#: 伪条款号：N.M 形态且 head 以数字紧接非 CJK（单位/字母）
_RE_NUMDOT = re.compile(r"^\d+\.\d+$")
_RE_NUM_UNIT = re.compile(r"^\d+(?:\.\d+)?\s*(?:mm|cm|m|kg|g|s|min|r|kV|V|A|N|Pa|MPa|℃|°C|Hz|W|J|m/s|r/min|\$)")

#: 逐字符拉开的连续单字符 token（≥3 个）。
#:
#: **2026-09-15 收敛循环第 1 轮根因（重复所有者）**：本判据曾在两处各写一份
#: —— `audit_text.spaced-run`（已修）与本文件。本文件这份仍用 `\w`，而
#: **Python 的 `\w` 含 CJK**，于是合法的「数值 + 空格 + 单位」排版
#: （`距坠落基准面 2 m 及 2 m 以上`、`dₙ ≤ 63 mm`）被判成逐字符拉开，
#: 64 部文档命中、样例肉眼全是**国标正确排版** → 整类都是误报。
#: （2026-09-15 二次修订）`spaced-run` 判据本身已**删除**（见 `classify_clause`
#: 内的删除理由与 `audit_text.CHECKS` 的注释）：命中 15/15 全是所有者刻意保留的
#: 合法形态，且残留劈开形态与"变量相乘"语法同形、判据无判别信号。
#: 故此处不再引用它，`ocr-wide-space-units` 类一并移除——避免「判据删了、
#: 引用还在」的悬空依赖（实测：删除当天本行 KeyError 直接打断整个循环）。
#: 恢复时须同时恢复此处引用与 `classify_clause` 中的分支，并用单位白名单锚定。

def _flat_frac_signature(text: str) -> bool:
    """扁平分式签名：纯公式行（无 CJK）同时含 ' - ' 与 ' + ' 且**无 '/'**。

    2026-09-15 修正：原正则漏了「无 '/'」条件 → GB/T 10541 的
    'F = (D H - (WH + Ww))/(WH + Ww) × 100 \\%'（分数线完好）被误报为
    formula-flattened。计数基础不能错。
    """
    for ln in (text or "").split("\n"):
        if re.search(r"[\u4e00-\u9fff]", ln) or "/" in ln:
            continue
        if re.search(r"\s-\s", ln) and re.search(r"\s\+\s", ln):
            return True
    return False

_RE_MFR_UNIT = re.compile(r"·\s*∞|τ\s*r\s*/\s*min|\\Nu")
#: 标点代换（本意 `表B,4`：标签里的点被识别成逗号）。
#: **2026-09-15 校准（两轮）**：原 `[A-Za-z],\d` 命中合法短句逗号
#: （'94℃变性1min,72℃延伸'）→ 收窄为单大写字母且前面不接字母；
#: 第 19 轮又发现仍命中**单位符号后的逗号**——'0.5µL,1µL,2µL,3µL 和 4µL'
#: （GB/T 10004-2008 6.6.17.3.1 合法的数值列），因 `µ` 不属于 `[A-Za-z]`。
#: 再排除「单位符号/数字」前缀，只保留**标签位**（行首、空格、CJK 之后）。
_RE_PUNCT_SUB = re.compile(r"(?<![A-Za-z0-9µμ°%])(?<![A-Za-z])[A-Z],\d")
#: 图内图例条目连排（`序号——名称` ≥2 次）= 标引序号说明混入正文的缺陷签名。
#: 目录行被切成条款（2026-09-15 轮次 22 实测 GB/T 10760.2：'5.1 试验样机1'、
#: '6.10 轴承温度的测定……………………………3'——点线+页码，20 条）
#:
#: **2026-09-15 新语料校准（误报收窄）**：原两分支
#:   ① `[…．.]{4,}\s*\d+\s*$`  点线（≥4 个 U+2026/ASCII 点）+ 页码
#:   ② `^\S+\s+\S{2,}\s*\d$`     单 token + 标题 + 数字（**无点线**）
#: 实测（全新语料 231 部）分支② 命中 20/23 条**全是误报**：
#:   - 正常条款正文末尾恰好是数字：'3.1 驾驶自动化分级原则\n3'、
#:     '5.1 检验方法概述\n2'（GB/T 40429-2021、GB/T 41534-2022）
#:   - 乱码行：'7.2.3 過動激結：阿4.8.90'（GB/T 13217.7-2023）
#: 而 3 条**真**目录行全带点线：'9.1 包装……13'、'10.1 技术文件……14'
#: （GB/T 28853-2012 目录页被切成条款——条款号序列
#:  '9.1,9.2,9.3,10.1,10.2,1,2,…' 确证：目录排在正文第 1 条之前）。
#: 故两分支统一为「**必须有点线**」——点线才是目录行的确定签名；
#: ASCII 点阈值 4→3 以收 `...13` 形态。判据可信度优先（宁少勿滥）。
#:
#: **2026-09-15 第二轮收窄（批次 2 · 500 部全新语料，5 条证据实例全审）**：
#: 「有点线 + 尾部数字」仍不够——实测 5 条证据 **4 条误报**，误报签名有两型：
#:   甲・**附录索引**（点线后是"表/图 + 字母编号"，编号末位数字冒充页码）：
#:     '密封橡皮 …… 表 A.1'、'内窗折页 …… 表 A. 10'（GB/T 4549.6-2004）。
#:     该型**整页都是索引**，属附录体例，不是目录混入正文。
#:   乙・**正文公式/量值恰好以数字收尾**（点线前是单位或公式片段，无描述词）：
#:     '= 1/3 (E rd₁/E rc₁ + E rd₂/…'（GB/T 36548-2024 效率计算公式）。
#: 补两个**必要条件**（仍以点线为签名，只是加严）：
#:   ① 点线**前**须有 ≥2 个连续描述字（汉字或 ≥3 拉丁字母）——排除乙型；
#:      且该描述字与点线之间只能隔空白（`[^\n]*?` 懒惰前缀会回溯、让描述字从行首
#:      任意位置取，实测把 `表 A.1 试验条件 …… 23` 里的 `A.1` 也算成描述字，
#:      故行首分支必须写 `[^\n]*?[ \t]*` 强制**紧邻**）。
#:   ② 点线**后**不得紧跟「表/图 + 字母编号」（必须有字母，如 `表 A.1`/`表A.1`；
#:      裸页码不属于此型，故字母位为**必需**而非可选——写成可选会误杀真目录行）。
#:      注意：只排「点线**紧后**就是表/图引用」的形态（甲型 `密封橡皮 …… 表 A.1`）；
#:      「表 A.1 试验条件 …… 23」这类**表的目录条目**仍命中（描述字=试验条件），
#:      因为表条目混入正文同样是真缺陷，不能一起排掉。
#: 收窄后 5 条证据 → **1 条真目录行**（GB/T 29798-2013 条款 14.5，
#:   内容为 '14.5 出错信息的扩展性 …… 108' 起共 10 行目录尾部；条款号序列
#:   '前置1, 10.2.3, 14.5, 1, 2, 3, …' 断裂确证目录尾部抢占正文 14.5 座位）。
#: 已知代价：纯拉丁描述（<3 字母，如 'Test …… 3'）与"点线后即表引用"两型不报；
#:   国标目录以中文条目为主，实测全语料无误伤，不为其放宽以免重新引入甲/乙型误报。
_RE_TOC_LINE = re.compile(
    r"(?:[\u4e00-\u9fff]+|\b[A-Za-z]{3})[ \t]*"              # ① 描述字（汉字≥1 或 拉丁≥3 整词）
    r"(?:…{2,}|[.．]{3,})[ \t]*"                            #   点线（字与点线间可留空格）
    r"(?![ \t]*[表图][ \t]*[A-Z][.．]?[ \t]*\d)"            # ② 紧后不得是表/图引用
    r"\d{1,3}[ \t]*$|"
    r"^\S+[^\n]*?[ \t]*(?:[\u4e00-\u9fff]+|\b[A-Za-z]{3})[ \t]*"  # 行首分支同加①（须紧邻）
    r"(?:…{2,}|[.．]{3,})"
    r"(?![ \t]*[表图][ \t]*[A-Z][.．]?[ \t]*\d)"             #   同加②
    r"[^\n]*?\s\d{1,3}$", re.M)


#: **数值术语条 vs 数值行的结构判别**（2026-09-15 批次4 实测）。
#:
#: 实测缺陷源（GB 17565-2022 条款 3.10）：
#:     `3.10\n615cm² 开口 615cm² opening\n最小边长尺寸为 152 mm 的矩形开口…`
#: 这是**合法术语条款**——`615cm² 开口` 是**被定义术语**（615cm² 是"开口"的限定名，
#: 紧跟英文对照），**定义正文另起一行**。而"伪条款号"要防的是**表格数值行/公式行**
#: 被切成条款，其形态是**数字+单位紧跟**（`1.0m/s<v≤2.0`、`2.3 mm 处测量`）。
#:
#: **为什么不判 `[来源:…]` 引用**：实测该类术语条的来源引用**在 MinerU 产物里被丢掉了**
#: （方括号块常被单独处理），所以"有引用"这个信号不可靠——第一版守卫就因此失效。
#: 结构信号则稳定：**数值片段独占一行、下一行才是散文** = 数值术语条。
_RE_NUM_TERM_LINE = re.compile(r"^(?:\d+(?:\.\d+)?\s*(?:mm|cm|m|kg|g|s|min|r|kV|V|A|N|Pa|MPa|℃|°C|Hz|W|J|m/s|r/min|\$)[^\n]*)\n\S")


def _is_numeric_term_clause(after: str) -> bool:
    """正文头是否为"**数值术语条**"（而非表格数值行被切成的伪条款）。

    判据：首行以"数字+单位"起头、且**次行还有内容**（术语行与其定义分行）。
    表格数值行是单行片段（`1.0m/s<v≤2.0 时，应按…` 这类不会满足"次行有内容"
    且首行恰为数值术语）；见 `_RE_NUM_TERM_LINE` 注释的实测对照。
    """
    return bool(_RE_NUM_TERM_LINE.match(after or ""))


def classify_clause(clause_no: str, head: str, conf: float) -> list[str]:
    """单条低置信条款 → 命中的问题类清单。"""
    hits: list[str] = []
    h = head or ""
    n = clause_no or ""

    # 伪条款号：号是 N.M 且正文以该数字紧接单位开头（正文数值行）
    if _RE_NUMDOT.fullmatch(n):
        after = re.sub(r"^\s*" + re.escape(n) + r"\s*", "", h, count=1)
        if after and _RE_NUM_UNIT.match(after):
            # 同下方 `head_unit_frag` 分支的守卫（见 `_RE_NUM_TERM_LINE` 注释）：
            # `615cm² 开口` 里的 `615cm` 会命中 `_RE_NUM_UNIT`（数字+单位前缀），
            # 但它是**被定义术语**（数值术语条），不是表格数值行。
            # 注：**不要用 `[来源:…]` 判**——实测该类术语条的引用在产物里被丢掉。
            if not _is_numeric_term_clause(after):
                hits.append("spurious-clause-number")
        # **2026-09-15 收敛循环第 9 轮校准**：判据改用**管线闸门的同一判据**
        # （`_RE_HEAD_UNIT_FRAG`，单一所有者），不再自写一份。原自写规则
        # `^[a-z]{1,4}(?![A-Za-z])` 会把合法术语条误报——
        # '3.4 ppm parts per million'（GB/T 12918-2023 实测）是英文缩写作
        # 标题的真条款；而 '1.0m/s<v≤2.0'、'mL，用40%'、'mmol/L氯化镁' 等
        # 数值片段仍照常命中。同一判据两处写 = 漂移根源（第 1 轮已吃过一次）。
        elif after and head_unit_frag_pat().match(after):
            # **2026-09-15 缩窄（批次4 实测误报）**：GB 17565-2022 的
            # `3.10\n615cm² 开口 615cm² opening\n最小边长尺寸为 152 mm 的矩形开口…`
            # ——这是**合法术语条款**：`615cm² 开口` 是**被定义术语**（615cm² 是
            # "开口"的限定名，紧跟英文对照），其后还有定义正文。
            # 而"伪条款号"要防的是**表格数值行/公式行**被切成条款。
            # 判别信号：**术语条款必带来源引用**（`[来源:GB …]`，GB/T 1.1 体例要求），
            # 表格数值行不会有。有引用 → 判为术语条款，不报。
            if not _is_numeric_term_clause(after):
                hits.append("spurious-clause-number")

    # 公式扁平（分数线丢失）。
    # **2026-09-15 收敛循环第 18 轮校准**：删掉 `_flat_frac_signature` 启发式分支。
    # 该启发式是「无 CJK 的公式行同时含 ' + ' 与 ' - ' 且无 '/'」，实测 4/4 命中
    # 都是**普通算式**而非分数线丢失：
    #   GB/T 1032-2023 7.9.3  'ₛ = + 25 - (20)'      （θs = θ + 25 - Δθ(20)）
    #   GB/T 13894-2023 A.3.3.2 'h c = h [ 1 + ₜ (t₁ - 2 0) ] (A.1)'
    #   GB/T 10002.2-2023 B.1.1 / GB/T 1029-2021 7.2.3.2.1 同理
    # 类本意是 **\frac 分数线语义丢失**，而 `\frac` 是确定信号 → 只留它。
    if "\\frac" in h:
        hits.append("formula-flattened")

    # 逐字符拉开（2026-09-15 **删除**，见下）。
    #
    # 原为 `_RE_WIDE_SPACE`（引用 `audit_text.spaced-run` 单一所有者）→ 产出
    # 本类。**删除理由（实测判定，新语料 231 部）**：
    #   1) 与 `spaced-run` 是**同一条判据产两个类名**（`_RE_WIDE_SPACE is
    #      dict(A.CHECKS)["spaced-run"]`），同一批文本被各计一遍 →
    #      两类恒等（实测各 9 部、命中原文完全相同），纯重复计数。
    #   2) 其命中经**所有者链**（`glue_ocr_spaced_units`，pipeline.py:401 实际调用）
    #      处理后**文本一个字符都不变** → 抓的全是所有者**刻意不动**的合法形态：
    #      '0.000 1 g'（四位分组精度值，门禁明令不动）、'0.75 p y'（公式变量积）、
    #      'King A M Q'（文献作者缩写）。
    #   3) 真缺陷（'1 . 0 mm'、'0.5U N'、'P 1 E'）**已被所有者修复**，
    #      修复后不再命中；而残留的劈开形态（'m m' vs 'X c'）与"变量相乘"
    #      **语法同形、原理上不可区分**——判据没有可用的判别信号。
    # 结论：判据已无真信号，继续上报只会淹没台账、把修复预算烧在假目标上
    # （纪律：误报判据要删除而非上报）。两类同时登记为「已删除判据」。
    # 复现条件：若新语料出现「已知单位被逐字符拉开」且所有者未修复的实例
    # （判据见 var/ocr-loop/evolve/instrument_fixes.jsonl 的 deleted_rules），
    # 应改为**带单位白名单**的窄判据重新启用。

    # 附录/表格低置信。
    # **2026-09-15 收敛循环第 2 轮根因（恒真判据）**：原判据只按"号是附录/表"
    # 命中，**从不看置信度**——实测第 2 轮 3 部的命中样例全是 conf=1.0 的普通
    # 附录条款（`附录B (资料性) 安全作业票的管理`、`附录A (资料性) 温度对压力的
    # 折减系数`），整类 43 部**全是误报**。类名即规格（lowconf）→ 补上置信度
    # 必要条件，判据回到它声明的语义。
    if conf < LOW_CONF and (n.startswith("附录") or n.startswith("表")
                            or "表A." in h or "表B." in h or "试验记录表" in h):
        hits.append("appendix-table-lowconf")

    # 图注/标引序号邻域 —— **2026-09-15 删除判据**（见下方理由链）。
    #
    # 历史：原判据三条里两条是误报源（'见图' 引用、条款以图号结尾）→ 第 4→5 轮
    # 收窄为"显式标引序号 或 图例条目连排"。2026-09-15 新语料批次2（500 部）实测：
    #   · 只认 `_RE_LEGEND_RUN` → 10 部命中**全是误报**（标准引用列表 + 表格尾部
    #     数字被当成图例条目：GB/T 25307-2010 B.1 条目=5、无图题、无图例头）；
    #   · 加"图例上下文（有图题）"条件想收窄 → **命中暴涨到 48 部**——因为国标
    #     正文几乎每张图都带图题，`图 N` + 任意 2 处破折号即命中，护栏写成了放大器。
    #   · 而**真图例已由所有者 `pipeline.strip_figure_legend_segment` 切除**
    #     （本轮同时补了它的两处覆盖缺口：图题前/后的无头图例），
    #     实测原本命中的 GB/T 23496-2009、GB/T 21386-2008 在修复后**不再命中**。
    # → 判据对"真图例已入正文"这一目标已无增量价值，只贡献噪声。按纪律
